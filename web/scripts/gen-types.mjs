// Generate TypeScript types from the export JSON Schemas (../schemas/v1).
// Usage: node scripts/gen-types.mjs [--check]   (--check fails if the committed types are stale)
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const webDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const schemaDir = path.join(webDir, "..", "schemas", "v1");
const outDir = path.join(webDir, "src", "types", "v1");
const check = process.argv.includes("--check");

const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

// Pydantic puts a "title" on every property; dropping them keeps one named type per model.
function stripPropertyTitles(node, keepTitle) {
  if (Array.isArray(node)) return node.map((n) => stripPropertyTitles(n, false));
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !keepTitle) continue;
    if (key === "$defs") {
      out[key] = Object.fromEntries(
        Object.entries(value).map(([name, def]) => [name, stripPropertyTitles(def, true)]),
      );
    } else {
      out[key] = stripPropertyTitles(value, false);
    }
  }
  return out;
}

const banner = "/* Generated by scripts/gen-types.mjs from schemas/v1. Do not edit. */";
const files = (await readdir(schemaDir)).filter((f) => f.endsWith(".schema.json")).sort();
const stale = [];
const docs = [];
const exported = new Map(); // type name -> first document that defines it (shared models repeat)
await mkdir(outDir, { recursive: true });

for (const file of files) {
  const doc = file.replace(".schema.json", "");
  const schema = stripPropertyTitles(JSON.parse(await readFile(path.join(schemaDir, file), "utf8")), true);
  schema.title = `${pascal(doc)}Document`;
  const ts = await compile(schema, schema.title, {
    bannerComment: banner,
    additionalProperties: false,
    style: { singleQuote: false, printWidth: 100 },
  });
  const target = path.join(outDir, `${doc}.ts`);
  docs.push(doc);
  for (const [, name] of ts.matchAll(/^export (?:interface|type) (\w+)/gm))
    if (!exported.has(name)) exported.set(name, doc);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== ts) stale.push(target);
  } else {
    await writeFile(target, ts);
  }
}

const namesOf = (d) => [...exported].filter(([, doc]) => doc === d).map(([n]) => n);
const index =
  `${banner}\n` +
  docs.map((d) => `export type { ${namesOf(d).join(", ")} } from "./${d}";`).join("\n") +
  "\n";
const indexPath = path.join(outDir, "index.ts");
if (check) {
  if ((await readFile(indexPath, "utf8").catch(() => "")) !== index) stale.push(indexPath);
  if (stale.length) {
    console.error(`Stale generated types (run npm run gen:types):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`types up to date (${docs.length} schemas)`);
} else {
  await writeFile(indexPath, index);
  console.log(`wrote ${docs.length} type files to ${path.relative(webDir, outDir)}`);
}
