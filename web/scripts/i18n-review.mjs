// Write docs/urdu-review.md: every UI string and translated export text, English beside Urdu,
// for the owner's review. Regenerate after any dictionary change: npm run i18n:review
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = async (p) => JSON.parse(await readFile(path.join(webDir, p), "utf8"));
const en = await read("src/i18n/en.json");
const ur = await read("src/i18n/ur.json");
const exportText = await read("src/i18n/export-text.ur.json");

const leaves = (obj, prefix = "") =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === "object" ? leaves(v, `${prefix}${k}.`) : [[`${prefix}${k}`, String(v)]],
  );
const cell = (s) => s.replaceAll("|", "\|").replaceAll("\n", " ");
const urMap = new Map(leaves(ur));

const lines = [
  "# Urdu translation review",
  "",
  "Generated by `npm run i18n:review` (web/) from `web/src/i18n/`. Do not edit here: change",
  "`ur.json` / `export-text.ur.json` (or tell Claude which rows to change) and regenerate.",
  "`{name}` placeholders are filled in by the site and must stay as they are. Digits stay Western.",
  "",
  "## Site text",
  "",
  "| Key | English | اردو |",
  "|---|---|---|",
  ...leaves(en).map(([k, v]) => `| \`${k}\` | ${cell(v)} | ${cell(urMap.get(k) ?? "**MISSING**")} |`),
  "",
  "## Fixed text from the data export",
  "",
  "| English (from the export) | اردو |",
  "|---|---|",
  ...Object.entries(exportText)
    .filter(([k]) => !k.startsWith("_"))
    .map(([k, v]) => `| ${cell(k)} | ${cell(v)} |`),
  "",
  "Data names (feeders, IBCs, grids, circles, census areas) and the weekly summary stay in English,",
  "as published; the Urdu equity page says the summary is available in English only.",
  "",
];
const out = path.join(webDir, "..", "docs", "urdu-review.md");
await writeFile(out, lines.join("\n"), "utf8");
console.log(`wrote ${path.relative(path.join(webDir, ".."), out)} (${leaves(en).length} keys)`);
